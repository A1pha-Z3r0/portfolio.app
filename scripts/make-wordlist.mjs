// Builds os/apps/words.js from a plain word list (whitespace or newline separated).
//
//   node scripts/make-wordlist.mjs <words.txt> [--dict <dictionary.txt>]
//
// Keeps lowercase a–z words of 2–7 letters (a 7-tile rack can't spell longer ones).
// With --dict, every word must also appear in the dictionary, and common inflections
// (cats, played, making, bigger, happily...) are added when the dictionary has them.
// ENABLE (public domain) works well as the dictionary:
//   https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
//
// To use a much bigger list, pass the dictionary itself as <words.txt>.
import { readFileSync, writeFileSync } from 'node:fs'

const args = process.argv.slice(2)
const input = args[0]
const dictPath = args.includes('--dict') ? args[args.indexOf('--dict') + 1] : null
if (!input) {
  console.error('usage: node scripts/make-wordlist.mjs <words.txt> [--dict <dictionary.txt>]')
  process.exit(1)
}

const read = (p) => readFileSync(p, 'utf8').toLowerCase().split(/\s+/).filter(Boolean)
const ok = (w) => /^[a-z]{2,7}$/.test(w)
const dict = dictPath ? new Set(read(dictPath)) : null
const valid = (w) => ok(w) && (!dict || dict.has(w))

const out = new Set()
for (const w of read(input)) {
  if (!valid(w)) continue
  out.add(w)
  if (!dict) continue
  const last = w.at(-1)
  const stem = w.slice(0, -1)
  const candidates = [
    w + 's', w + 'es', w + 'ed', w + 'd', w + 'ing', w + 'er', w + 'est', w + 'ly', w + 'y',
    stem + 'ing', // make -> making
    w + last + 'ed', w + last + 'ing', w + last + 'er', w + last + 'est', // stop -> stopped, big -> bigger
    stem + 'ies', stem + 'ied', stem + 'ier', stem + 'iest', stem + 'ily', // happy -> happily
  ]
  for (const c of candidates) if (valid(c)) out.add(c)
}

const words = [...out].sort()
writeFileSync(
  new URL('../os/apps/words.js', import.meta.url),
  `// Generated by scripts/make-wordlist.mjs (${words.length} words). Don't edit by hand.\n` +
    `export const WORDS = new Set(${JSON.stringify(words.join(' '))}.split(' '))\n`,
)
console.log(`wrote ${words.length} words to os/apps/words.js`)
